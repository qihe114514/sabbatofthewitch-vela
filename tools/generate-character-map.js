const fs = require('node:fs')
const path = require('node:path')

const projectRoot = path.resolve(__dirname, '..')
const scnRoot = path.join(projectRoot, 'src', 'common', 'scn')
const sdRoot = path.join(projectRoot, 'src', 'common', 'sd')
const outputJson = path.join(projectRoot, 'tools', 'generated', 'character-map.generated.json')
const outputModule = path.join(projectRoot, 'src', 'common', 'character-map.js')
const characters = new Set()
let previousMap = {}
if (fs.existsSync(outputJson)) {
  try { previousMap = JSON.parse(fs.readFileSync(outputJson, 'utf8')) } catch (error) { previousMap = {} }
}

for (const file of fs.readdirSync(scnRoot).filter((name) => name.endsWith('.txt'))) {
  for (const node of JSON.parse(fs.readFileSync(path.join(scnRoot, file), 'utf8'))) {
    if (node[0] !== 3 || !Array.isArray(node[3])) continue
    for (const entry of node[3]) {
      if (Array.isArray(entry) && entry[0]) characters.add(`${entry[0]}|${entry[2] == null ? '' : entry[2]}|${entry[3] == null ? '' : entry[3]}`)
    }
  }
}

const sprites = fs.readdirSync(sdRoot)
  .filter((name) => /\.(png|jpg|jpeg|webp)$/i.test(name))
  .sort()
const map = {}
for (const key of [...characters].sort()) {
  const name = key.split('|', 1)[0]
  if (previousMap[key] && fs.existsSync(path.join(projectRoot, 'src', previousMap[key].replace(/^\//, '')))) {
    map[key] = previousMap[key]
    continue
  }
  const sprite = sprites.find((file) => file.startsWith(name))
  if (sprite) map[key] = `/common/sd/${sprite}`
  else if (name.startsWith('ch_effect')) map[key] = '/common/overlay/集中線.png'
}

fs.mkdirSync(path.dirname(outputJson), { recursive: true })
fs.writeFileSync(outputJson, `${JSON.stringify(map, null, 2)}\n`)
fs.writeFileSync(outputModule, `// Generated by npm run index:visual.\nexport default ${JSON.stringify(map, null, 2)}\n`)
console.log(`角色映射已生成：${Object.keys(map).length}/${characters.size}`)

module.exports = { map, characters }
